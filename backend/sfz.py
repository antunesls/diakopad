"""Generates each pad's .sfz files.

DiakoPad runs one sfizz instance per pad (see backend/engine/). Each
instance loads a *bank*: every distinct sound the pad has in the live state
and in every saved scene (sample + volume + pan + tone), one region per
variant, selected by that pad's own MIDI CC (SCENE_CC_BASE + pad - 1).
Switching a scene is then one CC per pad - no process restart, no disk read,
and a note already ringing keeps its old sound (validated with sfizz_render
on sfizz 1.2.3: the CC only affects notes started after it).

padNN.sfz (live variant only) is still written next to the banks because
deploy/recover_pads_from_sfz.py rebuilds pad assignments from it.
"""
from __future__ import annotations

import os
from pathlib import Path

# Overridable via environment/config for the real deployment.
SFZ_BANK_DIR = Path(os.environ.get("DIAKOPAD_SFZ_BANK_DIR", Path(__file__).parent / "sfz_bank"))
SAMPLES_DIR = Path(__file__).parent / "samples"
NOTE_POLYPHONY = int(os.environ.get("DIAKOPAD_NOTE_POLYPHONY", "4"))
# CCs 102..117 are "undefined" in the MIDI spec; pad N uses 102 + N - 1.
# midi.py drops them from the controller -> pads forwarding, so no physical
# knob can ever flip a pad's variant.
SCENE_CC_BASE = int(os.environ.get("DIAKOPAD_SCENE_CC_BASE", "102"))
MAX_VARIANTS = 128  # CC values 0..127


def live_bank_dir() -> Path:
    return SFZ_BANK_DIR / "live"


def scene_cc(pad_number: int) -> int:
    return SCENE_CC_BASE + pad_number - 1


def _global_opcodes(settings: dict) -> list[str]:
    global_opcodes = [
        # velocity_sensitive=0 (default): every hit plays at the pad's set
        # volume regardless of how hard it's struck - "quiet unless you hit
        # it hard" was reported as a real usability problem.
        f"amp_veltrack={100 if settings.get('velocity_sensitive') == '1' else 0}",
        # Voice cap per pad (oldest voice is stolen, like Hydrogen's max-notes
        # queue): hammering a 6s cymbal otherwise stacks a new full-length
        # voice per hit - +4dB of pile-up into the limiter and a CPU spike.
        # 4 still lets fast repeats overlap naturally.
        f"note_polyphony={NOTE_POLYPHONY}",
        # 0.5ms minimum attack (drumkv1 does the same) avoids a click when a
        # sample doesn't start exactly at a zero crossing.
        "ampeg_attack=0.0005",
    ]
    if settings.get("sustain_mode", "1") == "1":
        # Ignore note-off entirely; the sample always plays to completion
        # once triggered, however briefly the pad is held.
        global_opcodes.append("loop_mode=one_shot")
    else:
        # Let note-off govern playback: release the pad and it stops
        # promptly (short release instead of ringing out or clicking).
        global_opcodes.append("ampeg_release=0.05")
    return global_opcodes


def _region_opcodes(variant: dict, note: int, trim: bool = False) -> list[str]:
    sample_path = (SAMPLES_DIR / variant["filename"]).resolve()
    opcodes = [
        f"sample={sample_path}",
        f"key={note}",
        f"pitch_keycenter={note}",
        f"volume={variant.get('volume_db', 6)}",
        f"pan={variant.get('pan', 0)}",
    ]
    if trim:
        # Auto-trim (sample_trim.py): skip leading silence / stop at the
        # end of the audible tail. Frames at the file's own sample rate.
        if variant.get("trim_start"):
            opcodes.append(f"offset={int(variant['trim_start'])}")
        if variant.get("trim_end") is not None:
            opcodes.append(f"end={int(variant['trim_end'])}")
    if variant.get("cutoff_hz"):
        opcodes += [f"cutoff={variant['cutoff_hz']:.0f}", "fil_type=lpf_2p"]
    return opcodes


def render_pad_sfz(pad: dict, settings: dict) -> str:
    lines = [
        "// Auto-generated by DiakoPad - do not edit by hand\n",
        f"<global> {' '.join(_global_opcodes(settings))}\n",
    ]
    if pad.get("filename"):
        lines.append(f"<region> {' '.join(_region_opcodes(pad, pad['midi_note'], _trim_on(settings)))}\n")
    return "".join(lines)


def _trim_on(settings: dict) -> bool:
    return settings.get("auto_trim", "1") == "1"


def render_pad_bank(pad_number: int, note: int, variants: list[dict], settings: dict) -> str:
    """One region per variant, gated on the pad's CC == variant index.
    A variant without a filename (pad empty in that scene) gets no region:
    selecting it silences the pad. Variant 0 is selected at startup."""
    cc = scene_cc(pad_number)
    lines = [
        "// Auto-generated by DiakoPad (pad bank) - do not edit by hand\n",
        f"<control> set_cc{cc}=0\n",
        f"<global> {' '.join(_global_opcodes(settings))}\n",
    ]
    for index, variant in enumerate(variants[:MAX_VARIANTS]):
        if variant.get("filename"):
            opcodes = _region_opcodes(variant, note, _trim_on(settings)) + [f"locc{cc}={index}", f"hicc{cc}={index}"]
            lines.append(f"<region> {' '.join(opcodes)}\n")
    return "".join(lines)


def write_pad_kit(pad_number: int, pad: dict, settings: dict) -> Path:
    """Writes this pad's live-only .sfz (padNN.sfz) and returns its path."""
    SFZ_BANK_DIR.mkdir(parents=True, exist_ok=True)
    path = SFZ_BANK_DIR / f"pad{pad_number:02d}.sfz"
    path.write_text(render_pad_sfz(pad, settings))
    return path


def write_pad_bank(pad_number: int, pad: dict, variants: list[dict], settings: dict, tag: str) -> Path:
    """Writes the bank a new sfizz generation loads, under its own file name
    (sfz_bank/live/padNN_<tag>.sfz) so the previous generation - still
    ringing out its last notes - never sees its file change; also refreshes
    padNN.sfz for the recovery script."""
    write_pad_kit(pad_number, pad, settings)
    live = live_bank_dir()
    live.mkdir(parents=True, exist_ok=True)
    path = live / f"pad{pad_number:02d}_{tag}.sfz"
    path.write_text(render_pad_bank(pad_number, pad["midi_note"], variants, settings))
    return path


# Kit-browse preview notes live above any real pad note (default layout is
# 36..51) on a fixed, kit-independent range, so re-pointing the dedicated
# preview sfizz instance at a new candidate kit never has to know what MIDI
# notes the physical pads are actually configured to.
PREVIEW_NOTE_BASE = 90


def render_preview_sfz(kit: dict) -> str:
    lines = ["// Auto-generated by DiakoPad - do not edit by hand\n"]
    for pad in kit.get("pads", []):
        if not pad.get("filename"):
            continue
        sample_path = (SAMPLES_DIR / pad["filename"]).resolve()
        note = PREVIEW_NOTE_BASE + pad["pad_number"] - 1
        opcodes = [
            f"sample={sample_path}",
            f"key={note}",
            f"pitch_keycenter={note}",
            "loop_mode=one_shot",
        ]
        if pad.get("trim_start"):
            opcodes.append(f"offset={int(pad['trim_start'])}")
        if pad.get("trim_end") is not None:
            opcodes.append(f"end={int(pad['trim_end'])}")
        lines.append(f"<region> {' '.join(opcodes)}\n")
    return "".join(lines)


def write_preview_kit(kit: dict) -> Path:
    """Writes the kit-browse preview instance's .sfz (one region per
    populated pad in `kit`, see storage.get_kit) and returns its path."""
    SFZ_BANK_DIR.mkdir(parents=True, exist_ok=True)
    path = SFZ_BANK_DIR / "preview.sfz"
    path.write_text(render_preview_sfz(kit))
    return path
